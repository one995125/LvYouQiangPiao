/** 足迹主路径静态回归检查；不读写本机或云端用户数据。 */
const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const app = JSON.parse(read('miniprogram/app.json'))
const config = read('miniprogram/constants/config.ts')
const store = read('miniprogram/stores/user-data.ts')
const scenic = read('miniprogram/pages/scenic/index.ts')
const mine = read('miniprogram/pages/mine/index.ts')
const mineView = read('miniprogram/pages/mine/index.wxml')
const page = read('miniprogram/packageExtra/pages/footprints/index.ts')

const extraPackage = app.subPackages.find((item) => item.root === 'packageExtra')
assert(extraPackage && extraPackage.pages.includes('pages/footprints/index'), '浏览历史页面未注册到扩展分包')
assert(scenic.includes('recordFootprint(scenic)'), '景区详情读取成功后未记录足迹')
assert(config.includes("footprints: 'sj_footprints'"), '足迹未使用统一 STORAGE_KEYS')
assert(store.includes('.slice(0, MAX_SYNC_FOOTPRINTS)'), '足迹未限制为最近 200 条')
assert(store.includes('footprintClearedAt'), '足迹清空缺少防复活水位')
assert(mine.includes("'/packageExtra/pages/footprints/index'"), '我的页面缺少足迹分包入口')
assert(mineView.includes('{{stats.footprints}}'), '我的页面缺少足迹统计')
assert(page.includes('getFootprints()'), '足迹页未读取同步快照')
assert(page.includes('clearFootprints()'), '足迹页缺少一键清空')
assert(!page.includes('getScenic('), '足迹页不得为每条记录并发读取景区')

assert(read('miniprogram/packageExtra/pages/footprints/index.wxml').includes('浏览历史'), '用户可见名称未更新为浏览历史')
console.log('浏览历史主路径检查通过：自动记录、200 条上限、我的入口、快照列表及防复活清空。')
